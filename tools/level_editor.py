import math
import os
import shutil
import tkinter as tk
from tkinter import ttk, filedialog, messagebox, colorchooser, simpledialog

try:
    from PIL import Image, ImageTk
except ImportError:
    Image = ImageTk = None

MAX_H, MAX_TEX, MAX_DIM = 8, 16, 64
ROOT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "wiigame")
LEVEL_DIR = os.path.join(ROOT, "levels")
TEX_DIR = os.path.join(ROOT, "textures")
FALLBACK = ["#b5533c", "#6c8ebf", "#82b366", "#d6b656", "#9673a6", "#d79b00", "#67ab9f", "#808080"]


class Level:
    def __init__(self, w=16, d=16):
        self.name = "Untitled"
        self.w, self.d = w, d
        self.sky = (100, 150, 255)
        self.floor_tex = 0
        self.spawn = [1.5, 1.5, 0.0]       # x, z, yaw (degrees, 0 = up/-z, 90 = right/+x)
        self.textures = []                 # relative paths, index = texture id
        self.cells = {}                    # (x, z) -> (height, texture id)

    def resize(self, nw, nd, dx=0, dz=0):
        """Resize to nw x nd; existing content moves by (dx, dz) cells (use for left/top edits)."""
        self.cells = {(x + dx, z + dz): v for (x, z), v in self.cells.items()
                      if 0 <= x + dx < nw and 0 <= z + dz < nd}
        self.spawn[0] = min(max(self.spawn[0] + dx, 0.5), nw - 0.5)
        self.spawn[1] = min(max(self.spawn[1] + dz, 0.5), nd - 0.5)
        self.w, self.d = nw, nd

    def save(self, path):
        with open(path, "w", newline="\n") as f:
            f.write("# Wii level v1 - generated by level_editor.py\n")
            f.write(f"NAME {self.name}\n")
            f.write(f"SIZE {self.w} {self.d}\n")
            f.write("SKY %d %d %d\n" % self.sky)
            f.write(f"FLOORTEX {self.floor_tex}\n")
            f.write("SPAWN %.2f %.2f %.1f\n" % tuple(self.spawn))
            for i, t in enumerate(self.textures):
                f.write(f"TEX {i} {t}\n")
            for (x, z), (h, t) in sorted(self.cells.items(), key=lambda kv: (kv[0][1], kv[0][0])):
                f.write(f"CELL {x} {z} {h} {t}\n")

    @classmethod
    def load(cls, path):
        lv = cls()
        with open(path) as f:
            for raw in f:
                line = raw.strip()
                if not line or line.startswith("#"):
                    continue
                p = line.split()
                key = p[0]
                if key == "NAME":
                    lv.name = line[5:].strip() or "Untitled"
                elif key == "SIZE":
                    lv.w, lv.d = int(p[1]), int(p[2])
                elif key == "SKY":
                    lv.sky = (int(p[1]), int(p[2]), int(p[3]))
                elif key == "FLOORTEX":
                    lv.floor_tex = int(p[1])
                elif key == "SPAWN":
                    lv.spawn = [float(p[1]), float(p[2]), float(p[3])]
                elif key == "TEX":
                    i = int(p[1])
                    while len(lv.textures) <= i:
                        lv.textures.append("")
                    lv.textures[i] = p[2]
                elif key == "CELL":
                    lv.cells[(int(p[1]), int(p[2]))] = (int(p[3]), int(p[4]))
        return lv


class Editor(tk.Tk):
    ZOOMS = (8, 12, 16, 24, 32, 48, 64)   # pixels per cell

    def __init__(self):
        super().__init__()
        self.level = Level()
        self.path = None
        self.images, self.sizes = {}, {}
        self.cell = 32
        self.tool = tk.StringVar(value="paint")
        self.height = tk.IntVar(value=1)
        self.yaw = tk.IntVar(value=0)
        self.status = tk.StringVar(value="Add a texture, then left-click the grid to paint.")
        self._build_ui()
        self.refresh_all()

    # ---------------------------------------------------------------- UI
    def _build_ui(self):
        self.geometry("1000x700")
        menu = tk.Menu(self)
        fm = tk.Menu(menu, tearoff=0)
        fm.add_command(label="New...", command=self.new_level)
        fm.add_command(label="Open...", command=self.open_level)
        fm.add_command(label="Save", command=self.save_level)
        fm.add_command(label="Save As...", command=lambda: self.save_level(True))
        fm.add_separator()
        fm.add_command(label="Quit", command=self.destroy)
        menu.add_cascade(label="File", menu=fm)
        lm = tk.Menu(menu, tearoff=0)
        lm.add_command(label="Set size...", command=self.resize_level)
        lm.add_command(label="Expand / shrink edges...", command=self.expand_level)
        lm.add_command(label="Rename...", command=self.rename_level)
        lm.add_command(label="Sky colour...", command=self.pick_sky)
        menu.add_cascade(label="Level", menu=lm)
        vm = tk.Menu(menu, tearoff=0)
        vm.add_command(label="Zoom in   (Ctrl +)", command=lambda: self.zoom(1))
        vm.add_command(label="Zoom out  (Ctrl -)", command=lambda: self.zoom(-1))
        vm.add_command(label="Fit to window", command=self.fit_zoom)
        menu.add_cascade(label="View", menu=vm)
        self.config(menu=menu)

        side = ttk.Frame(self, padding=8)
        side.pack(side="left", fill="y")

        tf = ttk.LabelFrame(side, text="Tool", padding=6)
        tf.pack(fill="x")
        for text, val in (("Paint", "paint"), ("Erase", "erase"), ("Spawn point", "spawn")):
            ttk.Radiobutton(tf, text=text, value=val, variable=self.tool).pack(anchor="w")

        pf = ttk.LabelFrame(side, text="Brush / spawn", padding=6)
        pf.pack(fill="x", pady=6)
        ttk.Label(pf, text=f"Height (1-{MAX_H})").grid(row=0, column=0, sticky="w")
        ttk.Spinbox(pf, from_=1, to=MAX_H, width=4, textvariable=self.height).grid(row=0, column=1)
        ttk.Label(pf, text="Spawn yaw (deg)").grid(row=1, column=0, sticky="w")
        ttk.Spinbox(pf, from_=0, to=359, increment=45, width=4, textvariable=self.yaw,
                    command=self.on_yaw).grid(row=1, column=1)

        xf = ttk.LabelFrame(side, text="Textures (PNG)", padding=6)
        xf.pack(fill="both", expand=True)
        self.listbox = tk.Listbox(xf, width=30, height=12, exportselection=False)
        self.listbox.pack(fill="both", expand=True)
        ttk.Button(xf, text="Add PNG...", command=self.add_texture).pack(fill="x", pady=(6, 0))
        ttk.Button(xf, text="Use selected as floor", command=self.set_floor).pack(fill="x", pady=2)
        self.floor_label = ttk.Label(xf, text="")
        self.floor_label.pack(anchor="w")

        ttk.Label(self, textvariable=self.status, relief="sunken", anchor="w").pack(side="bottom", fill="x")

        cf = ttk.Frame(self)
        cf.pack(side="right", fill="both", expand=True)
        self.canvas = tk.Canvas(cf, bg="#1e1e1e", highlightthickness=0)
        hs = ttk.Scrollbar(cf, orient="horizontal", command=self.canvas.xview)
        vs = ttk.Scrollbar(cf, orient="vertical", command=self.canvas.yview)
        self.canvas.configure(xscrollcommand=hs.set, yscrollcommand=vs.set)
        hs.pack(side="bottom", fill="x")
        vs.pack(side="right", fill="y")
        self.canvas.pack(fill="both", expand=True)

        self.canvas.bind("<Button-1>", self.on_paint)
        self.canvas.bind("<B1-Motion>", self.on_paint)
        for b in ("<Button-2>", "<Button-3>"):          # right click (Button-2 on macOS)
            self.canvas.bind(b, self.on_erase)
        for b in ("<B2-Motion>", "<B3-Motion>"):
            self.canvas.bind(b, self.on_erase)
        self.canvas.bind("<Motion>", self.on_move)
        self.canvas.bind("<MouseWheel>", lambda e: self.scroll(e.delta > 0, e.state))
        self.canvas.bind("<Button-4>", lambda e: self.scroll(True, e.state))
        self.canvas.bind("<Button-5>", lambda e: self.scroll(False, e.state))
        for k in ("<Control-plus>", "<Control-equal>", "<Control-KP_Add>"):
            self.bind(k, lambda e: self.zoom(1))
        for k in ("<Control-minus>", "<Control-KP_Subtract>"):
            self.bind(k, lambda e: self.zoom(-1))

    # ------------------------------------------------------- textures
    def load_images(self):
        self.images.clear()
        self.sizes.clear()
        for i, rel in enumerate(self.level.textures):
            path = os.path.join(ROOT, rel)
            try:
                if Image:
                    im = Image.open(path).convert("RGBA")
                    self.sizes[i] = im.size
                    self.images[i] = ImageTk.PhotoImage(im.resize((self.cell, self.cell)))
                else:
                    im = tk.PhotoImage(file=path)
                    self.sizes[i] = (im.width(), im.height())
                    self.images[i] = im.subsample(max(1, im.width() // self.cell))
            except Exception:
                pass            # missing file -> coloured fallback

    def refresh_list(self):
        sel = self.listbox.curselection()
        self.listbox.delete(0, "end")
        for i, rel in enumerate(self.level.textures):
            self.listbox.insert("end", f"{i}: {rel}")
        if self.level.textures:
            self.listbox.selection_set(sel[0] if sel and sel[0] < len(self.level.textures) else 0)
        self.floor_label.config(text=f"Floor texture id: {self.level.floor_tex}")

    def selected_tex(self):
        sel = self.listbox.curselection()
        return sel[0] if sel else 0

    def add_texture(self):
        if len(self.level.textures) >= MAX_TEX:
            messagebox.showwarning("Limit", f"The engine supports {MAX_TEX} textures per level.")
            return
        src = filedialog.askopenfilename(title="Choose a PNG", filetypes=[("PNG image", "*.png")])
        if not src:
            return
        name = os.path.basename(src).replace(" ", "_")
        os.makedirs(TEX_DIR, exist_ok=True)
        dst = os.path.join(TEX_DIR, name)
        if os.path.abspath(src) != os.path.abspath(dst):
            shutil.copyfile(src, dst)
        rel = "textures/" + name
        if rel not in self.level.textures:
            self.level.textures.append(rel)
        self.load_images()
        self.refresh_list()
        self.redraw()
        w, h = self.sizes.get(self.level.textures.index(rel), (0, 0))
        if w and (w & (w - 1) or h & (h - 1)):
            messagebox.showwarning("Texture size",
                                   f"{name} is {w}x{h}. Use power-of-two sizes (32, 64, 128...) "
                                   "so tiling works correctly on the Wii.")

    def set_floor(self):
        self.level.floor_tex = self.selected_tex()
        self.floor_label.config(text=f"Floor texture id: {self.level.floor_tex}")

    def pick_sky(self):
        c = colorchooser.askcolor(color="#%02x%02x%02x" % self.level.sky, title="Sky colour")
        if c and c[0]:
            self.level.sky = tuple(int(v) for v in c[0])

    # ----------------------------------------------------- drawing
    def redraw(self):
        self.canvas.delete("all")
        self.canvas.configure(scrollregion=(0, 0, self.level.w * self.cell, self.level.d * self.cell))
        for z in range(self.level.d):
            for x in range(self.level.w):
                self.draw_cell(x, z, spawn=False, clear=False)
        self.draw_spawn()

    def draw_cell(self, x, z, spawn=True, clear=True):
        tag = f"c{x}_{z}"
        if clear:
            self.canvas.delete(tag)
        x0, y0 = x * self.cell, z * self.cell
        cell = self.level.cells.get((x, z))
        if not cell:
            self.canvas.create_rectangle(x0, y0, x0 + self.cell, y0 + self.cell, fill="#2b2b2b",
                                         outline="#444", tags=tag)
        else:
            h, t = cell
            if t in self.images:
                self.canvas.create_image(x0, y0, anchor="nw", image=self.images[t], tags=tag)
            else:
                self.canvas.create_rectangle(x0, y0, x0 + self.cell, y0 + self.cell,
                                             fill=FALLBACK[t % len(FALLBACK)], tags=tag)
            self.canvas.create_rectangle(x0, y0, x0 + self.cell, y0 + self.cell, outline="black", tags=tag)
            font = ("TkDefaultFont", 9, "bold")
            if self.cell < 16:                       # too small for height numbers
                if spawn:
                    self.draw_spawn()
                return
            self.canvas.create_text(x0 + self.cell - 2, y0 + 3, anchor="ne", text=str(h),
                                    fill="black", font=font, tags=tag)
            self.canvas.create_text(x0 + self.cell - 3, y0 + 2, anchor="ne", text=str(h),
                                    fill="white", font=font, tags=tag)
        if spawn:
            self.draw_spawn()

    def draw_spawn(self):
        self.canvas.delete("spawn")
        sx, sz, yaw = self.level.spawn
        cx, cy = sx * self.cell, sz * self.cell
        r = math.radians(yaw)
        self.canvas.create_oval(cx - 8, cy - 8, cx + 8, cy + 8, fill="#e03030", outline="white",
                                width=2, tags="spawn")
        self.canvas.create_line(cx, cy, cx + math.sin(r) * 16, cy - math.cos(r) * 16,
                                fill="white", width=3, arrow="last", tags="spawn")

    # ------------------------------------------------------- mouse
    def cell_at(self, e):
        x = int(self.canvas.canvasx(e.x) // self.cell)
        z = int(self.canvas.canvasy(e.y) // self.cell)
        if 0 <= x < self.level.w and 0 <= z < self.level.d:
            return x, z
        return None

    def on_paint(self, e):
        c = self.cell_at(e)
        if not c:
            return
        if self.tool.get() == "erase":
            return self.on_erase(e)
        if self.tool.get() == "spawn":
            self.level.spawn = [c[0] + 0.5, c[1] + 0.5, self.safe_yaw()]
            return self.draw_spawn()
        if not self.level.textures:
            self.status.set("Add a texture first (Add PNG...).")
            return
        try:
            h = max(1, min(MAX_H, self.height.get()))
        except tk.TclError:
            h = 1
        self.level.cells[c] = (h, self.selected_tex())
        self.draw_cell(*c)

    def on_erase(self, e):
        c = self.cell_at(e)
        if c and c in self.level.cells:
            del self.level.cells[c]
            self.draw_cell(*c)

    def on_move(self, e):
        c = self.cell_at(e)
        if c:
            info = self.level.cells.get(c)
            self.status.set(f"Cell {c[0]}, {c[1]}   " +
                            (f"height {info[0]}, texture {info[1]}" if info else "empty"))

    def safe_yaw(self):
        try:
            return float(self.yaw.get() % 360)
        except tk.TclError:
            return 0.0

    def on_yaw(self):
        self.level.spawn[2] = self.safe_yaw()
        self.draw_spawn()

    # ------------------------------------------------------- files
    def refresh_all(self):
        self.load_images()
        self.refresh_list()
        self.yaw.set(int(self.level.spawn[2]))
        self.redraw()
        self.update_title()
    def ask_size(self, w=16, d=16):
        w = simpledialog.askinteger("Size", f"Width in cells (1-{MAX_DIM}):", initialvalue=w,
                                    minvalue=1, maxvalue=MAX_DIM, parent=self)
        if w is None:
            return None
        d = simpledialog.askinteger("Size", f"Depth in cells (1-{MAX_DIM}):", initialvalue=d,
                                    minvalue=1, maxvalue=MAX_DIM, parent=self)
        return None if d is None else (w, d)

    def new_level(self):
        size = self.ask_size()
        if not size:
            return
        old = self.level
        self.level = Level(*size)
        self.level.textures = list(old.textures)       # keep the texture palette
        self.path = None
        self.refresh_all()

    def update_title(self):
        lv = self.level
        f = f"  [{os.path.basename(self.path)}]" if self.path else ""
        self.title(f"Wii Level Editor - {lv.name} ({lv.w}x{lv.d}){f}")

    def apply_size(self, nw, nd, dx=0, dz=0):
        self.level.resize(nw, nd, dx, dz)
        self.redraw()
        self.update_title()

    def resize_level(self):
        size = self.ask_size(self.level.w, self.level.d)
        if size:
            self.apply_size(*size)

    def expand_level(self):
        lv = self.level
        dlg = tk.Toplevel(self)
        dlg.title("Expand / shrink edges")
        dlg.transient(self)
        dlg.grab_set()
        ttk.Label(dlg, justify="left",
                  text=f"Current size: {lv.w} x {lv.d}   (max {MAX_DIM} x {MAX_DIM})\n"
                       "Positive = add empty cells, negative = remove cells.").grid(
            row=0, column=0, columnspan=4, padx=10, pady=8)
        vars_ = {}
        for i, (key, label) in enumerate((("top", "Top"), ("bottom", "Bottom"),
                                          ("left", "Left"), ("right", "Right"))):
            vars_[key] = tk.IntVar(value=0)
            r, c = 1 + i // 2, (i % 2) * 2
            ttk.Label(dlg, text=label).grid(row=r, column=c, padx=6, pady=4, sticky="e")
            ttk.Spinbox(dlg, from_=-MAX_DIM, to=MAX_DIM, width=5,
                        textvariable=vars_[key]).grid(row=r, column=c + 1, padx=6)

        def apply():
            try:
                l, r, t, b = (vars_[k].get() for k in ("left", "right", "top", "bottom"))
            except tk.TclError:
                return
            nw, nd = lv.w + l + r, lv.d + t + b
            if not (1 <= nw <= MAX_DIM and 1 <= nd <= MAX_DIM):
                messagebox.showwarning("Size", f"That would give {nw} x {nd}; "
                                       f"allowed range is 1..{MAX_DIM} per side.", parent=dlg)
                return
            self.apply_size(nw, nd, l, t)
            dlg.destroy()

        bar = ttk.Frame(dlg)
        bar.grid(row=3, column=0, columnspan=4, pady=10)
        ttk.Button(bar, text="Apply", command=apply).pack(side="left", padx=6)
        ttk.Button(bar, text="Cancel", command=dlg.destroy).pack(side="left", padx=6)

    def zoom(self, d):
        i = self.ZOOMS.index(self.cell) if self.cell in self.ZOOMS else 4
        i = max(0, min(len(self.ZOOMS) - 1, i + d))
        if self.ZOOMS[i] != self.cell:
            self.cell = self.ZOOMS[i]
            self.load_images()
            self.redraw()
            self.status.set(f"Zoom: {self.cell}px per cell")

    def fit_zoom(self):
        self.update_idletasks()
        cw, ch = self.canvas.winfo_width(), self.canvas.winfo_height()
        best = self.ZOOMS[0]
        for z in self.ZOOMS:
            if self.level.w * z <= cw and self.level.d * z <= ch:
                best = z
        self.cell = best
        self.load_images()
        self.redraw()

    def scroll(self, up, state):
        if state & 0x4:                       # Ctrl + wheel = zoom
            self.zoom(1 if up else -1)
        elif state & 0x1:                     # Shift + wheel = horizontal
            self.canvas.xview_scroll(-3 if up else 3, "units")
        else:
            self.canvas.yview_scroll(-3 if up else 3, "units")

    def rename_level(self):
        n = simpledialog.askstring("Level name", "Name:", initialvalue=self.level.name, parent=self)
        if n:
            self.level.name = n.strip()
            self.update_title()
    def open_level(self):
        os.makedirs(LEVEL_DIR, exist_ok=True)
        p = filedialog.askopenfilename(initialdir=LEVEL_DIR, filetypes=[("Level", "*.lvl")])
        if not p:
            return
        try:
            self.level = Level.load(p)
        except Exception as ex:
            return messagebox.showerror("Open failed", str(ex))
        self.path = p
        self.refresh_all()

    def save_level(self, as_new=False):
        if as_new or not self.path:
            os.makedirs(LEVEL_DIR, exist_ok=True)
            n = 1
            while os.path.exists(os.path.join(LEVEL_DIR, f"level{n}.lvl")):
                n += 1                                   # suggest the next free level number
            p = filedialog.asksaveasfilename(initialdir=LEVEL_DIR, defaultextension=".lvl",
                                             initialfile=f"level{n}.lvl", filetypes=[("Level", "*.lvl")])
            if not p:
                return
            self.path = p
        self.level.spawn[2] = self.safe_yaw()
        self.level.save(self.path)
        self.status.set(f"Saved {self.path}")
        self.update_title()
if __name__ == "__main__":
    Editor().mainloop()
